const PREFIXES = ['EXE', 'ALC', 'ARC', 'DIS']
const OTHER_STATUS = ['进行中', '已完结', '封存']

function pick(list) {
  return list[Math.floor(Math.random() * list.length)]
}

/**
 * 生成一批任务（刷新看板用）。
 * 每次刷新都生成全新编号，并保证 2~3 项「招募中」可领取任务；
 * 已完成任务按编号去重，重复编号不会再计入权限点。
 * @param {number} n 任务数量
 */
export function generateMissions(n = 6) {
  const pool = MISSION_POOL.slice()
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[pool[i], pool[j]] = [pool[j], pool[i]]
  }

  const used = new Set()
  const recruit = 2 + Math.floor(Math.random() * 2) // 2~3 项可领取

  return pool.slice(0, n).map((p, idx) => {
    let code
    do {
      code = `${pick(PREFIXES)}-${1000 + Math.floor(Math.random() * 9000)}`
    } while (used.has(code))
    used.add(code)

    return {
      ...p,
      code,
      status: idx < recruit ? '招募中' : pick(OTHER_STATUS)
    }
  })
}
