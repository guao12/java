/** 兜底：任何未单独编写的记录，也能生成一份可读的详情 */
function fallback(log) {
  return {
    op: `${log.deptLabel || '执行部'} · 常规归档`,
    date: '时间未登记',
    site: '地点未登记',
    level: log.req || 2,
    summary: log.process || '该任务暂无摘要。',
    brief: ['任务简报未登记。'],
    canon: '',
    steps: [{ t: '执行过程', d: log.process || '——' }],
    outcome: { result: log.result || '——', cost: '未登记。', note: '' },
    figures: log.personKey ? [log.personKey] : [],
    relics: [],
    quote: ''
  }
}

/**
 * 组装详情：把 MISSION_META（重内容）与 ARCHIVE_MISSION_LOGS（来源记录）合并。
 * @param {object} log ARCHIVE_MISSION_LOGS 中的一条
 */
export function logDetail(log) {
  if (!log) return null
  const extra = MISSION_META[`${log.code}|${log.person}`] || {}
  const base = fallback(log)
  const d = { ...base, ...extra }
  return {
    ...log,
    ...d,
    // 人物 key → 是否命中人物志（决定能否跳转）
    figures: (d.figures || []).map((k) => {
      const p = CHARACTER_GALLERY.find((c) => c.key === k)
      return { key: k, name: p ? p.name : k, link: !!p }
    })
  }
}

/** 详情页按「编号 + 人名」定位；人名用 URL 编码以兼容中文 */
export function logPath(log) {
  return `/log/${log.code}/${encodeURIComponent(log.person)}`
}

